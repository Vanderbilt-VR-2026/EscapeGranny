// MainMenuSceneBuilder.cs
//
// Builds the whole main menu scene in one click, so nobody has to set up the XR rig, UI canvas,
// panels and button wiring by hand.
//
// How to use:
//   Menu: Tools > Escape Granny > Build Main Menu.
//   It (re)creates Assets/_Game/Scenes/MainMenu.unity containing:
//     - XR Origin (XR Rig) from the XRI Starter Assets sample, at (0, 0, 0)
//     - Granny's house: HouseBuilder's generated shell with its horror lighting (moonlight, fog, one
//       dim lamp per room), and MenuRoomPicker, which starts the player in a random spawn room
//       facing its most open side. Plus an invisible safety floor (the rig has gravity).
//     - an EventSystem with XR UI Input Module
//     - GameSession (remembers role + weapon), RoleClaimService (fake "other player" checkboxes)
//       and MenuController (shows one panel at a time, fading each one in)
//     - MenuPlacer (HeadsetMenuPlacer): hides the menu until the headset is tracking, then shows it
//       2 m ahead of wherever the player is facing (closer, and smaller, if a wall is in the way)
//     - MenuAudio: ambience loop + button sounds (generated by MenuSoundGenerator into _Game/Audio)
//     - Menu: the root that MenuPlacer moves. It holds
//         Dust        slow floating dust specks around the menu
//         MenuLight   a dim lantern-like light that lights the 3D models on the menu
//         MenuCanvas  world-space canvas: flickering title with a red glow behind it, corner
//                     brackets, a controls hint, and four panels:
//           HomePanel          tagline + PLAY
//           RoleSelectPanel    Granny / Prisoner boxes on the left; the picked character turns on a
//                              stand on the right + START + BACK (RoleSelector; the characters come
//                              from RoleCardModelBuilder)
//           GrannyLoadoutPanel Axe / Knife / Gun / Bomb cards + CONFIRM + BACK (WeaponLoadout)
//           PrisonerBriefPanel briefing card + READY + BACK               (PrisonerBriefing)
//     - XR Device Simulator, if its sample has been imported (keyboard and mouse fake VR for Macs).
//       Tagged EditorOnly, so it's only in the Editor, never in a headset build.
//   Then it applies the moodboard look (MenuThemeApplier) and puts the 3D weapon models on the
//   loadout buttons (WeaponModelBuilder).
//
//   This file decides WHERE things go; MenuThemeApplier decides colours, fonts and sizes, finding
//   objects by the names given here (Glow, Corner, Divider, Step, Accent, Stats, Tag, ...).
//
//   Running it again asks before overwriting the scene, and anything changed by hand in the scene
//   is lost. To tweak the look, edit Assets/_Game/Settings/MenuTheme.asset and rebuild.

using System.IO;
using UnityEditor;
using UnityEditor.Events;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.SceneManagement;
using UnityEngine.UI;
using UnityEngine.XR.Interaction.Toolkit.UI;

public static class MainMenuSceneBuilder
{
    const string ScenePath = "Assets/_Game/Scenes/MainMenu.unity";
    const string RigPrefabPath =
        "Assets/Samples/XR Interaction Toolkit/3.3.2/Starter Assets/Prefabs/XR Origin (XR Rig).prefab";
    const string GlowTexturePath = "Assets/_Game/Textures/MenuGlow.png";
    const string DustMaterialPath = "Packages/com.unity.render-pipelines.universal/Runtime/Materials/ParticlesUnlit.mat";

    // Newer XRI simulator first, then the classic one.
    static readonly string[] SimulatorPrefabNames = { "XR Interaction Simulator", "XR Device Simulator" };

    // Canvas is 960 x 600 UI units; at 0.002 m per unit that is 1.92 m x 1.2 m in the world.
    // Its centre is (0, 0), so x runs -480..480 and y runs -300..300.
    static readonly Vector2 CanvasSize = new Vector2(960, 600);
    const float CanvasScale = 0.002f;
    // Only where the menu sits while editing; in Play mode MenuPlacer moves it in front of the player.
    static readonly Vector3 MenuPosition = new Vector3(0f, 1.5f, 2f);

    // Shared layout rows (UI units), top to bottom.
    const float TitleY = 215f, StepY = 148f, HeadingY = 116f, DividerY = 86f;
    const float ActionY = -215f, HintY = -272f;
    static readonly Vector2 ActionSize = new Vector2(260, 70);
    static readonly Vector2 BackPosition = new Vector2(-370, ActionY);
    static readonly Vector2 BackSize = new Vector2(150, 56);

    static readonly (WeaponType weapon, string tag, string description)[] Weapons =
    {
        (WeaponType.Axe, "NEAR", "Near. Get within arm's reach and swing to kill."),
        (WeaponType.Knife, "NEAR", "Near. Get within arm's reach and thrust to kill."),
        (WeaponType.Gun, "FAR", "Far. Shoot from a distance, but ammo is limited."),
        (WeaponType.Bomb, "THROWN", "Far. Throw it at a target."),
    };

    [MenuItem("Tools/Escape Granny/Build Main Menu")]
    public static void BuildMainMenu()
    {
        var rigPrefab = AssetDatabase.LoadAssetAtPath<GameObject>(RigPrefabPath);
        if (rigPrefab == null)
        {
            EditorUtility.DisplayDialog("Main Menu Builder",
                "Couldn't find the XR Origin (XR Rig) prefab at:\n" + RigPrefabPath +
                "\n\nImport it via Window > Package Manager > XR Interaction Toolkit > Samples > Starter Assets.",
                "OK");
            return;
        }

        if (AssetDatabase.LoadAssetAtPath<SceneAsset>(ScenePath) != null &&
            !EditorUtility.DisplayDialog("Main Menu Builder",
                ScenePath + " already exists. Rebuild it? Anything you changed in it by hand will be lost.",
                "Rebuild", "Cancel"))
            return;

        if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            return;

        EnsureFolder("Assets/_Game");
        EnsureFolder("Assets/_Game/Scenes");

        // Default scene = Main Camera + Directional Light. The rig brings its own camera.
        Scene scene = EditorSceneManager.NewScene(NewSceneSetup.DefaultGameObjects, NewSceneMode.Single);
        var defaultCamera = GameObject.Find("Main Camera");
        if (defaultCamera != null) Object.DestroyImmediate(defaultCamera);

        var rig = (GameObject)PrefabUtility.InstantiatePrefab(rigPrefab, scene);
        rig.transform.position = Vector3.zero;

        // The house the menu floats in: the same generated shell and horror lighting as the game's
        // house (HouseBuilder), not House_Bishal itself, so the shared game scene is never touched.
        HouseBuilder.BuildHouse();
        HouseBuilder.ApplyHorrorLighting();
        var roomPicker = new GameObject("MenuRoomPicker").AddComponent<MenuRoomPicker>();
        var pickerSo = new SerializedObject(roomPicker);
        pickerSo.FindProperty("rig").objectReferenceValue = rig.transform;
        pickerSo.ApplyModifiedPropertiesWithoutUndo();

        // Safety net: an invisible floor just below the basement, under and around the house. The rig
        // has gravity, so if the player ever ends up off the house floors they don't fall forever.
        // (Not at ground level: it would block the stairwell down to the basement.)
        var floor = new GameObject("Floor (invisible)");
        floor.transform.position = new Vector3(9f, -3.35f, 7f); // top face at y = -3.3, centred on the house
        floor.AddComponent<BoxCollider>().size = new Vector3(60f, 0.1f, 60f);

        new GameObject("EventSystem", typeof(EventSystem), typeof(XRUIInputModule));
        new GameObject("GameSession", typeof(GameSession));
        var claims = new GameObject("RoleClaimService").AddComponent<LocalRoleClaimService>();
        var controller = new GameObject("MenuController").AddComponent<MenuController>();

        var rigCamera = rig.GetComponentInChildren<Camera>();
        var menuRoot = new GameObject("Menu").transform;
        menuRoot.position = MenuPosition;
        AddDust(menuRoot);
        AddMenuLight(menuRoot);
        var canvas = BuildCanvas(menuRoot, rigCamera);
        AddMenuPlacer(menuRoot, rigCamera.transform, rig.transform);
        AddMenuAudio();

        var home = BuildHomePanel(canvas.transform, controller);
        var roleSelect = BuildRoleSelectPanel(canvas.transform, controller, claims);
        var loadout = BuildWeaponLoadoutPanel(canvas.transform, controller);
        var brief = BuildPrisonerBriefPanel(canvas.transform, controller);

        var so = new SerializedObject(controller);
        so.FindProperty("homePanel").objectReferenceValue = home;
        so.FindProperty("roleSelectPanel").objectReferenceValue = roleSelect;
        so.FindProperty("grannyLoadoutPanel").objectReferenceValue = loadout.gameObject;
        so.FindProperty("prisonerBriefPanel").objectReferenceValue = brief;
        so.ApplyModifiedPropertiesWithoutUndo();

        // Only Home visible while editing; MenuController does the same in Play mode.
        // To edit another panel, untick HomePanel and tick that one in the Hierarchy.
        roleSelect.SetActive(false);
        loadout.gameObject.SetActive(false);
        brief.SetActive(false);

        bool simulatorAdded = AddDeviceSimulator(scene);
        bool themed = MenuThemeApplier.Apply(canvas);
        int models = WeaponModelBuilder.AddModels(loadout);

        EditorSceneManager.SaveScene(scene, ScenePath);
        AssetDatabase.Refresh();

        string msg = "Built " + ScenePath + ". Press Play to try it.";
        if (!themed)
            msg += "\n\nThe moodboard theme was skipped: MenuTheme is missing a font (see the Console).";
        if (models < Weapons.Length)
            msg += $"\n\nOnly {models} of {Weapons.Length} weapon models were added (see the Console).";
        if (!simulatorAdded)
            msg += "\n\nNo XR Device Simulator found. On a Mac, import it via Window > Package Manager > " +
                   "XR Interaction Toolkit > Samples > XR Device Simulator, then rebuild.";
        EditorUtility.DisplayDialog("Main Menu Builder", msg, "OK");
    }

    // The canvas plus everything that stays on screen behind every panel.
    static GameObject BuildCanvas(Transform menuRoot, Camera eventCamera)
    {
        var canvasGo = new GameObject("MenuCanvas", typeof(RectTransform));
        canvasGo.transform.SetParent(menuRoot, false);
        var canvas = canvasGo.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.WorldSpace;
        canvas.worldCamera = eventCamera;
        canvasGo.AddComponent<CanvasScaler>().dynamicPixelsPerUnit = 10f; // keeps text crisp in world space
        canvasGo.AddComponent<TrackedDeviceGraphicRaycaster>();           // lets XR rays hit this canvas

        var rt = (RectTransform)canvasGo.transform;
        rt.sizeDelta = CanvasSize;
        rt.localPosition = Vector3.zero;
        rt.localScale = Vector3.one * CanvasScale;

        var background = CreateUiObject("Background", canvasGo.transform);
        Stretch(background);
        background.gameObject.AddComponent<Image>();

        // A soft red light bleeding out from behind the title. Created before the title so it draws behind.
        var glow = CreateImage("Glow", canvasGo.transform, new Vector2(0, TitleY - 10), new Vector2(900, 300));
        glow.sprite = LoadOrCreateGlowSprite();
        glow.gameObject.AddComponent<MenuFlicker>();

        AddCornerBrackets(canvasGo.transform);

        var title = CreateText("Title", canvasGo.transform, "Escape the Granny", 64);
        Place(title.rectTransform, new Vector2(0, TitleY), new Vector2(900, 120));
        title.gameObject.AddComponent<MenuFlicker>();

        var hint = CreateText("Hint", canvasGo.transform,
            "POINT WITH YOUR CONTROLLER   ·   PULL THE TRIGGER TO SELECT", 22);
        Place(hint.rectTransform, new Vector2(0, HintY), new Vector2(900, 30));
        return canvasGo;
    }

    // Thin L-shaped brackets in the four corners, like a camera viewfinder.
    static void AddCornerBrackets(Transform canvas)
    {
        const float inset = 18f, length = 48f, thickness = 3f;
        float x = CanvasSize.x / 2f - inset, y = CanvasSize.y / 2f - inset;
        foreach (var (sx, sy) in new[] { (-1f, 1f), (1f, 1f), (-1f, -1f), (1f, -1f) })
        {
            CreateImage("Corner", canvas, new Vector2(sx * (x - length / 2f), sy * y), new Vector2(length, thickness));
            CreateImage("Corner", canvas, new Vector2(sx * x, sy * (y - length / 2f)), new Vector2(thickness, length));
        }
    }

    // Slow dust specks drifting around the menu: makes the black void feel like a dark room.
    // Few, small particles, so it's cheap on Quest.
    static void AddDust(Transform menuRoot)
    {
        var go = new GameObject("Dust");
        go.transform.SetParent(menuRoot, false);
        go.transform.localPosition = new Vector3(0f, 0f, -0.5f); // between the player and the menu

        var ps = go.AddComponent<ParticleSystem>();
        ps.Stop(true, ParticleSystemStopBehavior.StopEmittingAndClear); // settings below need it stopped

        var main = ps.main;
        main.loop = true;
        main.prewarm = true;  // already full of dust when the menu appears
        main.duration = 10f;
        main.startLifetime = 12f;
        main.startSpeed = 0.02f;
        main.startSize = new ParticleSystem.MinMaxCurve(0.006f, 0.018f);
        main.startColor = new Color(0.91f, 0.88f, 0.83f, 0.45f);
        main.maxParticles = 60;
        main.simulationSpace = ParticleSystemSimulationSpace.Local; // moves with the menu when it's placed

        var emission = ps.emission;
        emission.rateOverTime = 5f;

        var shape = ps.shape;
        shape.shapeType = ParticleSystemShapeType.Box;
        shape.scale = new Vector3(3f, 2f, 1.5f);

        var noise = ps.noise;
        noise.enabled = true;
        noise.strength = 0.03f;
        noise.frequency = 0.2f;

        // Fade each speck in and out so none of them pop.
        var gradient = new Gradient();
        gradient.SetKeys(
            new[] { new GradientColorKey(Color.white, 0f), new GradientColorKey(Color.white, 1f) },
            new[] { new GradientAlphaKey(0f, 0f), new GradientAlphaKey(1f, 0.2f),
                    new GradientAlphaKey(1f, 0.8f), new GradientAlphaKey(0f, 1f) });
        var colorOverLifetime = ps.colorOverLifetime;
        colorOverLifetime.enabled = true;
        colorOverLifetime.color = gradient;

        var material = AssetDatabase.LoadAssetAtPath<Material>(DustMaterialPath);
        if (material == null) Debug.LogWarning("[MainMenuSceneBuilder] Couldn't find " + DustMaterialPath + "; the dust will look pink.");
        go.GetComponent<ParticleSystemRenderer>().sharedMaterial = material;
    }

    // A dim warm light just in front of the menu, like a lantern: lights the 3D characters and weapons
    // (the horror lighting is very dark) and spills a little onto the room around the menu.
    static void AddMenuLight(Transform menuRoot)
    {
        var go = new GameObject("MenuLight");
        go.transform.SetParent(menuRoot, false);
        go.transform.localPosition = new Vector3(0f, 0.3f, -0.7f); // toward the player
        var light = go.AddComponent<Light>();
        light.type = LightType.Point;
        light.color = new Color(1f, 0.82f, 0.62f);
        light.intensity = 1.2f;
        light.range = 2.5f;
        light.shadows = LightShadows.None; // shadows are expensive on Quest
    }

    static void AddMenuPlacer(Transform menu, Transform head, Transform rig)
    {
        var placer = new GameObject("MenuPlacer").AddComponent<HeadsetMenuPlacer>();
        var so = new SerializedObject(placer);
        so.FindProperty("menu").objectReferenceValue = menu;
        so.FindProperty("head").objectReferenceValue = head;
        so.FindProperty("rig").objectReferenceValue = rig; // lets it turn the player away from a wall
        so.ApplyModifiedPropertiesWithoutUndo();
    }

    static void AddMenuAudio()
    {
        var audio = new GameObject("MenuAudio").AddComponent<MenuAudio>();
        var so = new SerializedObject(audio);
        so.FindProperty("ambience").objectReferenceValue = MenuSoundGenerator.Ambience;
        so.FindProperty("hover").objectReferenceValue = MenuSoundGenerator.Hover;
        so.FindProperty("click").objectReferenceValue = MenuSoundGenerator.Click;
        so.FindProperty("confirm").objectReferenceValue = MenuSoundGenerator.Confirm;
        so.ApplyModifiedPropertiesWithoutUndo();
    }

    // Big buttons that move the player forward get the deep confirm sound instead of the click.
    static void MarkMainAction(Button button)
    {
        var so = new SerializedObject(button.GetComponent<MenuButtonFx>());
        so.FindProperty("mainAction").boolValue = true;
        so.ApplyModifiedPropertiesWithoutUndo();
    }

    static GameObject BuildHomePanel(Transform canvas, MenuController controller)
    {
        var panel = CreateUiObject("HomePanel", canvas);
        Stretch(panel);

        // The heading text is replaced by MenuTheme's tagline when the theme is applied.
        var tagline = CreateText("Heading", panel, "Two players. One key. Five minutes.", 32);
        Place(tagline.rectTransform, new Vector2(0, 125), new Vector2(900, 50));
        CreateImage("Divider", panel, new Vector2(0, 92), new Vector2(120, 3));

        var play = CreateButton("PlayButton", panel, "PLAY", new Vector2(0, -15), new Vector2(340, 110));
        MarkMainAction(play);
        UnityEventTools.AddPersistentListener(play.onClick, controller.ShowRoleSelect);

        var subtext = CreateText("Subtext", panel, "ASYMMETRIC VR HORROR   ·   2 PLAYERS", 22);
        Place(subtext.rectTransform, new Vector2(0, -105), new Vector2(900, 30));
        return panel.gameObject;
    }

    // Fortnite-locker style: the two roles as boxes on the left; the picked one's character turns on a
    // stand on the right, with its name and facts beside it. START sits under the character.
    static GameObject BuildRoleSelectPanel(Transform canvas, MenuController controller, LocalRoleClaimService claims)
    {
        var panel = CreatePanel("RoleSelectPanel", canvas, "Choose your role", "Step 1 of 2");
        var selector = panel.AddComponent<RoleSelector>();

        var granny = CreateRoleBox(panel.transform, "Granny", "THE HUNTER", new Vector2(-300, 10),
            out var grannyHighlight, out var grannyTaken);
        var prisoner = CreateRoleBox(panel.transform, "Prisoner", "THE HUNTED", new Vector2(-300, -120),
            out var prisonerHighlight, out var prisonerTaken);

        // The stage: where the picked character stands (x -20..260, y -175..75).
        var stage = CreateUiObject("Stage", panel.transform);
        Place(stage, new Vector2(120, -50), new Vector2(280, 250));

        var empty = CreateUiObject("EmptyPreview", stage);
        Stretch(empty);
        var hint = CreateText("PickHint", empty, "PICK A ROLE", 32);
        Stretch(hint.rectTransform);

        var grannyPreview = CreateRolePreview(stage, "Granny", "THE HUNTER",
            "Picks one weapon\nSees all, moves slower\nMap finds the prisoner");
        var prisonerPreview = CreateRolePreview(stage, "Prisoner", "THE HUNTED",
            "No weapons, a spotlight\nFind the key, escape\nHide to survive");
        // Rim light colours: brighter versions of the theme's role colours, since lights look dimmer than UI.
        // (Models are measured while their previews are still active; inactive renderers have no size.)
        RoleCardModelBuilder.AddModels(grannyPreview, prisonerPreview,
            new Color(1f, 0.3f, 0.25f), new Color(0.35f, 0.55f, 1f));
        prisonerPreview.gameObject.SetActive(false);
        empty.gameObject.SetActive(false); // RoleSelector shows the right one in Play mode

        var start = CreateButton("StartButton", panel.transform, "START", new Vector2(120, ActionY), ActionSize);
        MarkMainAction(start);
        var back = CreateButton("BackButton", panel.transform, "BACK", BackPosition, BackSize);

        UnityEventTools.AddPersistentListener(granny.onClick, selector.SelectGranny);
        UnityEventTools.AddPersistentListener(prisoner.onClick, selector.SelectPrisoner);
        UnityEventTools.AddPersistentListener(start.onClick, selector.OnStartPressed);
        UnityEventTools.AddPersistentListener(back.onClick, controller.ShowHome);

        var so = new SerializedObject(selector);
        so.FindProperty("menuController").objectReferenceValue = controller;
        so.FindProperty("grannyButton").objectReferenceValue = granny;
        so.FindProperty("prisonerButton").objectReferenceValue = prisoner;
        so.FindProperty("startButton").objectReferenceValue = start;
        so.FindProperty("grannyHighlight").objectReferenceValue = grannyHighlight;
        so.FindProperty("prisonerHighlight").objectReferenceValue = prisonerHighlight;
        so.FindProperty("grannyTakenLabel").objectReferenceValue = grannyTaken;
        so.FindProperty("prisonerTakenLabel").objectReferenceValue = prisonerTaken;
        so.FindProperty("grannyPreview").objectReferenceValue = grannyPreview.gameObject;
        so.FindProperty("prisonerPreview").objectReferenceValue = prisonerPreview.gameObject;
        so.FindProperty("emptyPreview").objectReferenceValue = empty.gameObject;
        so.FindProperty("roleClaimService").objectReferenceValue = claims;
        so.ApplyModifiedPropertiesWithoutUndo();
        return panel;
    }

    // A role box on the left: a colour stripe on top, the role name, a subtitle, and a "TAKEN" stamp
    // shown when the other player has the role.
    static Button CreateRoleBox(Transform parent, string role, string subtitle, Vector2 position,
        out GameObject highlight, out GameObject takenLabel)
    {
        var box = CreateOption(parent, role, role.ToUpper(), position, new Vector2(300, 110), out highlight);
        box.name = role + "Portrait";
        var boxRt = (RectTransform)box.transform;

        var accent = CreateImage("Accent", boxRt, Vector2.zero, Vector2.zero);
        accent.rectTransform.anchorMin = new Vector2(0, 1);
        accent.rectTransform.anchorMax = new Vector2(1, 1);
        accent.rectTransform.pivot = new Vector2(0.5f, 1f);
        accent.rectTransform.sizeDelta = new Vector2(0, 6);

        Place((RectTransform)boxRt.Find("Label"), new Vector2(0, 14), new Vector2(280, 60));
        var sub = CreateText("Subtitle", boxRt, subtitle, 22);
        Place(sub.rectTransform, new Vector2(0, -30), new Vector2(280, 26));

        var taken = CreateText("TakenLabel", boxRt, "TAKEN", 64);
        Place(taken.rectTransform, new Vector2(0, -4), new Vector2(280, 90));
        taken.rectTransform.localRotation = Quaternion.Euler(0, 0, 8); // tilted like a rubber stamp
        taken.gameObject.SetActive(false);
        takenLabel = taken.gameObject;
        return box;
    }

    // One role's preview, filling the stage: a coloured glow behind where the character stands
    // (RoleCardModelBuilder adds the character, its stand and rim light), and the name and facts to
    // the right of the stage.
    static RectTransform CreateRolePreview(RectTransform stage, string role, string subtitle, string stats)
    {
        var preview = CreateUiObject(role + "Preview", stage);
        Stretch(preview);

        var glow = CreateImage("StageGlow", preview, new Vector2(0, 0), new Vector2(340, 320));
        glow.sprite = LoadOrCreateGlowSprite();

        // Info column right of the stage (canvas x 245..455).
        const float infoX = 230f, infoWidth = 210f;
        var name = CreateText("RoleName", preview, role.ToUpper(), 56);
        Place(name.rectTransform, new Vector2(infoX, 80), new Vector2(infoWidth, 70));
        name.alignment = TextAnchor.MiddleLeft;

        var sub = CreateText("Subtitle", preview, subtitle, 22);
        Place(sub.rectTransform, new Vector2(infoX, 36), new Vector2(infoWidth, 28));
        sub.alignment = TextAnchor.MiddleLeft;

        var statsText = CreateText("Stats", preview, stats, 22);
        Place(statsText.rectTransform, new Vector2(infoX, -40), new Vector2(infoWidth, 110)); // keep each fact to one line
        statsText.alignment = TextAnchor.UpperLeft;
        return preview;
    }

    static WeaponLoadout BuildWeaponLoadoutPanel(Transform canvas, MenuController controller)
    {
        var panel = CreatePanel("GrannyLoadoutPanel", canvas, "Choose your weapon", "Step 2 of 2");
        var loadout = panel.AddComponent<WeaponLoadout>();

        var so = new SerializedObject(loadout);
        var optionsProp = so.FindProperty("options");
        optionsProp.arraySize = Weapons.Length;

        var cardSize = new Vector2(180, 160);
        for (int i = 0; i < Weapons.Length; i++)
        {
            var (weapon, tag, description) = Weapons[i];
            var button = CreateOption(panel.transform, weapon.ToString(), weapon.ToString().ToUpper(),
                new Vector2(-315 + i * 210, -45), cardSize, out var highlight);
            UnityEventTools.AddIntPersistentListener(button.onClick, loadout.SelectWeapon, (int)weapon);

            // Range tag just above the card, on the option so it doesn't grow on hover.
            var tagText = CreateText("Tag", button.transform.parent, tag, 22);
            Place(tagText.rectTransform, new Vector2(0, cardSize.y / 2f + 24), new Vector2(180, 26));

            var element = optionsProp.GetArrayElementAtIndex(i);
            element.FindPropertyRelative("weapon").enumValueIndex = (int)weapon;
            element.FindPropertyRelative("button").objectReferenceValue = button;
            element.FindPropertyRelative("highlight").objectReferenceValue = highlight;
            element.FindPropertyRelative("description").stringValue = description;
        }

        var descriptionText = CreateText("Description", panel.transform, "", 24);
        Place(descriptionText.rectTransform, new Vector2(0, -150), new Vector2(900, 40));

        var confirm = CreateButton("ConfirmButton", panel.transform, "CONFIRM", new Vector2(0, ActionY), ActionSize);
        MarkMainAction(confirm);
        UnityEventTools.AddPersistentListener(confirm.onClick, loadout.OnConfirmPressed);
        var back = CreateButton("BackButton", panel.transform, "BACK", BackPosition, BackSize);
        UnityEventTools.AddPersistentListener(back.onClick, controller.ShowRoleSelect);

        so.FindProperty("menuController").objectReferenceValue = controller;
        so.FindProperty("descriptionText").objectReferenceValue = descriptionText;
        so.FindProperty("confirmButton").objectReferenceValue = confirm;
        so.ApplyModifiedPropertiesWithoutUndo();
        return loadout;
    }

    static GameObject BuildPrisonerBriefPanel(Transform canvas, MenuController controller)
    {
        var panel = CreatePanel("PrisonerBriefPanel", canvas, "Your briefing", "Step 2 of 2");
        var briefing = panel.AddComponent<PrisonerBriefing>();

        // A dark card with a red bar down its left edge, like a mission objective screen.
        var card = CreateImage("BriefCard", panel.transform, new Vector2(0, -40), new Vector2(760, 210));
        var accent = CreateImage("Accent", card.transform, Vector2.zero, Vector2.zero);
        accent.rectTransform.anchorMin = Vector2.zero;
        accent.rectTransform.anchorMax = new Vector2(0, 1);
        accent.rectTransform.pivot = new Vector2(0f, 0.5f);
        accent.rectTransform.sizeDelta = new Vector2(6, 0);

        // Filled in by PrisonerBriefing when the panel is shown.
        var body = CreateText("BriefingText", card.transform, "(briefing text)", 24);
        Stretch(body.rectTransform);
        body.rectTransform.offsetMin = new Vector2(36, 16);  // left, bottom padding
        body.rectTransform.offsetMax = new Vector2(-24, -16); // right, top padding
        body.alignment = TextAnchor.MiddleLeft;

        var ready = CreateButton("ReadyButton", panel.transform, "READY", new Vector2(0, ActionY), ActionSize);
        MarkMainAction(ready);
        UnityEventTools.AddPersistentListener(ready.onClick, briefing.OnReadyPressed);
        var back = CreateButton("BackButton", panel.transform, "BACK", BackPosition, BackSize);
        UnityEventTools.AddPersistentListener(back.onClick, controller.ShowRoleSelect);

        var so = new SerializedObject(briefing);
        so.FindProperty("menuController").objectReferenceValue = controller;
        so.FindProperty("briefingText").objectReferenceValue = body;
        so.ApplyModifiedPropertiesWithoutUndo();
        return panel;
    }

    // A full-size, transparent panel with a small step label, a heading and a short red divider.
    // The canvas title stays visible above it.
    static GameObject CreatePanel(string name, Transform canvas, string heading, string step)
    {
        var panel = CreateUiObject(name, canvas);
        Stretch(panel);

        var stepText = CreateText("Step", panel, step.ToUpper(), 22);
        Place(stepText.rectTransform, new Vector2(0, StepY), new Vector2(900, 28));

        var headingText = CreateText("Heading", panel, heading.ToUpper(), 32);
        Place(headingText.rectTransform, new Vector2(0, HeadingY), new Vector2(900, 50));

        CreateImage("Divider", panel, new Vector2(0, DividerY), new Vector2(120, 3));
        return panel.gameObject;
    }

    // A pickable option: a highlight frame (hidden until picked) peeking out 10 units around a
    // button. The option object is named <name>Option and the button <name>Button; MenuThemeApplier
    // colours them by those names.
    static Button CreateOption(Transform parent, string name, string label, Vector2 position, Vector2 size,
        out GameObject highlight)
    {
        var option = CreateUiObject(name + "Option", parent);
        option.anchoredPosition = position;
        option.sizeDelta = size + new Vector2(20, 20);

        // Created first so it draws behind the button, peeking out as a frame.
        var frame = CreateUiObject("Highlight", option);
        Stretch(frame);
        frame.gameObject.AddComponent<Image>().raycastTarget = false;
        frame.gameObject.AddComponent<MenuPulse>(); // softly pulses while picked
        frame.gameObject.SetActive(false);
        highlight = frame.gameObject;

        return CreateButton(name + "Button", option, label, Vector2.zero, size);
    }

    static Button CreateButton(string name, Transform parent, string label, Vector2 position, Vector2 size)
    {
        var rt = CreateUiObject(name, parent);
        rt.sizeDelta = size;
        rt.anchoredPosition = position;
        var image = rt.gameObject.AddComponent<Image>();
        var button = rt.gameObject.AddComponent<Button>();
        button.targetGraphic = image;
        rt.gameObject.AddComponent<MenuButtonFx>(); // grows on hover, punches on click

        var text = CreateText("Label", rt, label, 40);
        Stretch(text.rectTransform);
        return button;
    }

    static bool AddDeviceSimulator(Scene scene)
    {
        foreach (string prefabName in SimulatorPrefabNames)
        {
            foreach (string guid in AssetDatabase.FindAssets(prefabName + " t:Prefab"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (Path.GetFileNameWithoutExtension(path) != prefabName) continue;

                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                var simulator = (GameObject)PrefabUtility.InstantiatePrefab(prefab, scene);
                // EditorOnly objects are left out of builds. On a Quest the simulator would remove the
                // real headset (it hides every other HMD), freezing the view.
                simulator.tag = "EditorOnly";
                return true;
            }
        }
        return false;
    }

    // A white, round, soft-edged blob (opaque centre fading to clear edges), saved once as a sprite.
    // Tinted and stretched by the Image that uses it.
    static Sprite LoadOrCreateGlowSprite()
    {
        if (!File.Exists(GlowTexturePath))
        {
            EnsureFolder("Assets/_Game/Textures");
            const int size = 128;
            var texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
            for (int y = 0; y < size; y++)
            for (int x = 0; x < size; x++)
            {
                float dx = (x + 0.5f) / size * 2f - 1f, dy = (y + 0.5f) / size * 2f - 1f;
                float a = Mathf.SmoothStep(0f, 1f, 1f - Mathf.Sqrt(dx * dx + dy * dy));
                texture.SetPixel(x, y, new Color(1f, 1f, 1f, a * a));
            }
            File.WriteAllBytes(GlowTexturePath, texture.EncodeToPNG());
            Object.DestroyImmediate(texture);
            AssetDatabase.ImportAsset(GlowTexturePath);

            var importer = (TextureImporter)AssetImporter.GetAtPath(GlowTexturePath);
            importer.textureType = TextureImporterType.Sprite;
            importer.alphaIsTransparency = true;
            importer.mipmapEnabled = false;
            importer.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<Sprite>(GlowTexturePath);
    }

    static RectTransform CreateUiObject(string name, Transform parent)
    {
        var go = new GameObject(name, typeof(RectTransform));
        go.transform.SetParent(parent, false);
        return (RectTransform)go.transform;
    }

    // A decorative Image (plain rectangle unless given a sprite) that doesn't block the controller ray.
    static Image CreateImage(string name, Transform parent, Vector2 position, Vector2 size)
    {
        var image = CreateUiObject(name, parent).gameObject.AddComponent<Image>();
        Place(image.rectTransform, position, size);
        image.raycastTarget = false;
        return image;
    }

    // Legacy UI Text: works without TextMeshPro's essential resources. MenuThemeApplier sets the
    // real fonts, sizes and colours afterwards.
    static Text CreateText(string name, Transform parent, string content, int fontSize)
    {
        var text = CreateUiObject(name, parent).gameObject.AddComponent<Text>();
        text.text = content;
        text.font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        text.fontSize = fontSize;
        text.alignment = TextAnchor.MiddleCenter;
        text.color = Color.white;
        text.raycastTarget = false;
        return text;
    }

    // Centre-anchored at a position (UI units from the parent's centre) with a fixed size.
    static void Place(RectTransform rt, Vector2 position, Vector2 size)
    {
        rt.anchorMin = rt.anchorMax = new Vector2(0.5f, 0.5f);
        rt.anchoredPosition = position;
        rt.sizeDelta = size;
    }

    static void Stretch(RectTransform rt)
    {
        rt.anchorMin = Vector2.zero;
        rt.anchorMax = Vector2.one;
        rt.offsetMin = Vector2.zero;
        rt.offsetMax = Vector2.zero;
    }

    static void EnsureFolder(string path)
    {
        if (AssetDatabase.IsValidFolder(path)) return;
        int slash = path.LastIndexOf('/');
        AssetDatabase.CreateFolder(path.Substring(0, slash), path.Substring(slash + 1));
    }
